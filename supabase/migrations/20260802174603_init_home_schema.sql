-- ============================================================================
-- Migration: init_home_schema
-- Purpose:   Core schema for the portfolio home page data.
--            Migrates the data previously hardcoded in
--            features/home/components/* into Supabase tables.
--
-- Tables created:
--   hero       -> single-row profile used by /api/hero and app/page.tsx
--   status     -> current availability status (latest row wins)
--   projects   -> portfolio projects (features/home/.../projects/data)
--   services   -> service cards (features/home/.../services/data)
--   timeline   -> career/learning timeline (features/home/.../timeline/data)
--   clients    -> logos shown on the home page
--   reviews    -> testimonials
--   messages   -> contact form submissions (POST /api/contact)
--   contacts   -> contact entries with a typed kind (email, github, ...)
--   contents   -> CMS-style content sections (hero, about, footer, ...)
--
-- Access model:
--   * Public read  -> anon + authenticated can SELECT published content
--   * Public write -> anon can INSERT into messages (contact form)
--   * Admin writes -> content is managed via the service_role key / dashboard
--                     (bypasses RLS), no direct write policies are granted.
-- ============================================================================

begin;

-- ---------------------------------------------------------------------------
-- 1. Enums
-- ---------------------------------------------------------------------------

-- Typed contact kinds: email, facebook, github, ...
create type public.contact_type as enum (
  'email',
  'phone',
  'location',
  'github',
  'linkedin',
  'facebook',
  'upwork',
  'website',
  'twitter',
  'instagram',
  'whatsapp',
  'telegram',
  'youtube',
  'other'
);

-- Availability status values: available, focus, busy, ...
create type public.availability_status as enum (
  'available',
  'focus',
  'busy',
  'offline',
  'hiring'
);

-- Content sections managed through the contents table
create type public.content_section as enum (
  'hero',
  'about',
  'footer',
  'privacy',
  'terms',
  'general'
);

-- ---------------------------------------------------------------------------
-- 2. Tables
-- ---------------------------------------------------------------------------

-- Single-row hero profile (read by /api/hero and app/page.tsx)
create table public.hero (
  id            bigint generated by default as identity primary key,
  name          text not null,
  title         text not null,
  description   text not null default '',
  cv_url        text,                              -- public URL of the CV in the 'rabin' storage bucket
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Current availability status; the app reads the latest created_at row
create table public.status (
  id                bigint generated by default as identity primary key,
  status_type       public.availability_status not null default 'available',
  status_text       text not null,                 -- human readable line, e.g. "Available for new projects"
  current_position  text,                          -- e.g. "Full Stack Developer at Truenary Solutions"
  location          text,                          -- e.g. "Hetauda, Nepal"
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table public.projects (
  id                bigint generated by default as identity primary key,
  name              text not null,
  type              text not null,                 -- e.g. 'Chat', 'Ecommerce Platform'
  project_type      text not null default '',      -- 'Personal' | 'Professional' | ''
  description       text not null default '',
  technologies_used text[] not null default '{}',
  images            text[] not null default '{}',  -- paths/URLs, first image is the card cover
  task_completed    text[] not null default '{}',
  url_btn_links     jsonb not null default '[]'::jsonb, -- [{"name": "...", "link": "..."}]
  sort_order        int not null default 0,
  is_published      boolean not null default true,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create table public.services (
  id            bigint generated by default as identity primary key,
  title         text not null,
  skills        text[] not null default '{}',      -- devicon classes / icon urls
  sort_order    int not null default 0,
  is_published  boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table public.timeline (
  id            bigint generated by default as identity primary key,
  date          text not null,                     -- e.g. '2022 January'
  title         text not null,
  task_done     text not null default '',
  icon_name     text not null default 'devicon-nextjs-plain',
  icon_class    text not null default '',
  sort_order    int not null default 0,
  is_published  boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table public.clients (
  id            bigint generated by default as identity primary key,
  name          text not null,
  logo          text not null default '',          -- logo URL
  url           text,                              -- client website
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table public.reviews (
  id            bigint generated by default as identity primary key,
  client_name   text not null,
  review_text   text not null,
  rating        int not null default 5 check (rating between 1 and 5),
  avatar        text not null default '',
  role          text not null default '',
  project_name  text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Contact form submissions (POST /api/contact). anon may INSERT, never SELECT.
create table public.messages (
  id            bigint generated by default as identity primary key,
  name          text not null,
  email         text not null,
  tel           text,
  message       text not null,
  created_at    timestamptz not null default now()
);

-- Typed contact entries: email, facebook, github, phone, ...
create table public.contacts (
  id            bigint generated by default as identity primary key,
  contact_type  public.contact_type not null,
  label         text not null,                     -- display label, e.g. 'Email', 'GitHub'
  value         text not null,                     -- raw value, e.g. 'robinjsl321@gmail.com'
  url           text,                              -- clickable URL, e.g. 'mailto:...' or 'https://...'
  icon          text not null default '',          -- material icon / devicon class
  sort_order    int not null default 0,
  is_public     boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- CMS-style content sections: hero, about, footer, privacy, terms, ...
-- NOTE: a `hero` table is kept for backward compatibility with the current
-- /api/hero and app/page.tsx queries. The hero section below mirrors it.
-- Once the API routes read from `contents`, the `hero` table can be dropped.
create table public.contents (
  id            bigint generated by default as identity primary key,
  section       public.content_section not null,
  title         text not null,                     -- e.g. 'Hero', 'About Me'
  subtitle      text,
  body          text,                              -- markdown/plain text content
  image_url     text,                              -- hero / section image
  metadata      jsonb not null default '{}'::jsonb, -- flexible extra fields
  is_published  boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 3. updated_at trigger
-- ---------------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Only trigger internals need this; revoke public execute (defense in depth).
revoke all on function public.set_updated_at() from public, anon, authenticated;

do $$
declare
  t text;
begin
  foreach t in array array[
    'hero', 'status', 'projects', 'services', 'timeline',
    'clients', 'reviews', 'contacts', 'contents'
  ] loop
    execute format(
      'create trigger trg_%1$s_updated_at before update on public.%1$s
       for each row execute function public.set_updated_at()', t);
  end loop;
end;
$$;

-- ---------------------------------------------------------------------------
-- 4. Indexes (match the access patterns in the API routes)
-- ---------------------------------------------------------------------------

create index projects_sort_order_idx     on public.projects (sort_order, id);
create index projects_project_type_idx   on public.projects (project_type);
create index services_sort_order_idx     on public.services (sort_order, id);
create index timeline_sort_order_idx     on public.timeline (sort_order, id);
create index contacts_type_sort_idx      on public.contacts (contact_type, sort_order, id);
create index contents_section_idx        on public.contents (section, is_published);
create index status_created_at_idx       on public.status (created_at desc);
create index messages_created_at_idx     on public.messages (created_at desc);
create index reviews_created_at_idx      on public.reviews (created_at desc);

-- ---------------------------------------------------------------------------
-- 5. Row Level Security
--    Public read for published content, anon INSERT for the contact form.
--    Content writes are performed with the service_role key (bypasses RLS).
-- ---------------------------------------------------------------------------

alter table public.hero      enable row level security;
alter table public.status    enable row level security;
alter table public.projects  enable row level security;
alter table public.services  enable row level security;
alter table public.timeline  enable row level security;
alter table public.clients   enable row level security;
alter table public.reviews   enable row level security;
alter table public.messages  enable row level security;
alter table public.contacts  enable row level security;
alter table public.contents  enable row level security;

-- Single-row profile tables: everything is public
create policy "hero_public_read" on public.hero
  for select to anon, authenticated using (true);

create policy "status_public_read" on public.status
  for select to anon, authenticated using (true);

-- Published content only
create policy "projects_public_read" on public.projects
  for select to anon, authenticated using (is_published);

create policy "services_public_read" on public.services
  for select to anon, authenticated using (is_published);

create policy "timeline_public_read" on public.timeline
  for select to anon, authenticated using (is_published);

create policy "clients_public_read" on public.clients
  for select to anon, authenticated using (true);

create policy "reviews_public_read" on public.reviews
  for select to anon, authenticated using (true);

create policy "contacts_public_read" on public.contacts
  for select to anon, authenticated using (is_public);

create policy "contents_public_read" on public.contents
  for select to anon, authenticated using (is_published);

-- Contact form: anyone can submit, nobody reads via the Data API
create policy "messages_public_insert" on public.messages
  for insert to anon, authenticated with check (true);

-- ---------------------------------------------------------------------------
-- 6. Grants (expose tables to the Data API for anon/authenticated)
-- ---------------------------------------------------------------------------

grant select on public.hero, public.status, public.projects, public.services,
  public.timeline, public.clients, public.reviews, public.contacts, public.contents
  to anon, authenticated;

grant insert on public.messages to anon, authenticated;

commit;
